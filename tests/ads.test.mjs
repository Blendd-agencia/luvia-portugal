import {test} from 'node:test';
import assert from 'node:assert/strict';
import {initializeAds, setAdsChoice, trackQuoteSuccess, ADS_DESTINATION} from '../lib/ads.ts';
test('confirmed leads only, consent, deduplication, preview isolation and consent withdrawal', () => {
 const storage=()=>{const map=new Map();return {getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)}};
 globalThis.localStorage=storage();globalThis.sessionStorage=storage();
 const events=[];const scripts=[];
 globalThis.window={location:{hostname:'preview.vercel.app'},dispatchEvent:e=>events.push(e)};
 globalThis.document={createElement:()=>({}),head:{appendChild:s=>scripts.push(s)}};
 const id='e16d4ad9-c698-4ad6-a826-a4d407b5e42c';
 initializeAds(false);
 assert.equal(trackQuoteSuccess({ok:true},id),false);
 setAdsChoice('granted');
 for(const response of [null,{}, {ok:false},{error:'failed'}]) assert.equal(trackQuoteSuccess(response,id),false);
 assert.equal(trackQuoteSuccess({ok:true},id),true);
 assert.equal(trackQuoteSuccess({ok:true},id),false);
 assert.equal(events.length,1);assert.equal(scripts.length,0);
 window.location.hostname='luvia.pt';initializeAds(true);
 assert.equal(scripts.length,1);
 const second='b16d4ad9-c698-4ad6-a826-a4d407b5e42c';
 assert.equal(trackQuoteSuccess({ok:true},second),true);
 assert.equal(trackQuoteSuccess({ok:true},second),false);
 const calls=window.dataLayer.map(args=>Array.from(args));
 const conversions=calls.filter(args=>args[0]==='event');
 assert.deepEqual(conversions,[['event','conversion',{send_to:ADS_DESTINATION,transaction_id:second}]]);
 assert.equal(calls[0][0],'consent');assert.equal(calls[0][2].ad_storage,'denied');
 setAdsChoice('denied');assert.equal(trackQuoteSuccess({ok:true},'c16d4ad9-c698-4ad6-a826-a4d407b5e42c'),false);
 setAdsChoice('granted');assert.equal(Array.from(window.dataLayer.at(-1))[2].ad_storage,'granted');
 assert.equal(scripts.length,1);
});
